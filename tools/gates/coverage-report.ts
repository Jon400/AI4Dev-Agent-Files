import type { PlannedCase, TestPlan } from './parsers/test-plan'
import { CASE_PROJECTS, type ReportedTest } from './test-inventory'

export type CaseOutcome = 'passed' | 'failed' | 'flaky' | 'not run'

// One outcome per case over every result in a run: all passed → passed, all failed →
// failed, both → flaky (the same case passed and failed across repeats).
export function caseOutcomes(runTests: ReportedTest[]): Map<string, CaseOutcome> {
  const statuses = new Map<string, Set<string>>()
  for (const test of runTests) {
    const caseId = test.caseIds[0]
    if (!caseId) continue
    const seen = statuses.get(caseId) ?? new Set<string>()
    for (const result of test.results) {
      if (result.status === 'skipped') continue
      seen.add(result.status === 'passed' ? 'passed' : 'failed')
    }
    statuses.set(caseId, seen)
  }
  const outcomes = new Map<string, CaseOutcome>()
  for (const [caseId, seen] of statuses) {
    outcomes.set(
      caseId,
      seen.size === 2
        ? 'flaky'
        : seen.has('passed')
          ? 'passed'
          : seen.has('failed')
            ? 'failed'
            : 'not run'
    )
  }
  return outcomes
}

export interface CoverageInput {
  plans: TestPlan[]
  tests: ReportedTest[]
  outcomes: Map<string, CaseOutcome>
  runId: string | undefined
  generatedAt: Date
}

const cell = (value: string) => value.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ')

// .orchestrate/coverage-report.md: requirement → cases → tests → last result, plus planned
// vs automated per area. Computed; never edited by hand.
export function buildCoverageReport(input: CoverageInput): string {
  const testsByCase = new Map<string, ReportedTest[]>()
  for (const test of input.tests.filter(candidate =>
    (CASE_PROJECTS as readonly string[]).includes(candidate.project)
  )) {
    for (const caseId of test.caseIds)
      testsByCase.set(caseId, [...(testsByCase.get(caseId) ?? []), test])
  }
  const automated = (plannedCase: PlannedCase) => (testsByCase.get(plannedCase.id) ?? []).length > 0
  const outcome = (caseId: string) => input.outcomes.get(caseId) ?? 'not run'

  const lines: string[] = [
    '# Coverage report',
    '',
    `Generated by \`npm run gate\` at ${input.generatedAt.toISOString()}. Last run: ${input.runId ?? 'none yet'}.`,
    'Computed from `.test/*/test-plan.md`, `playwright test --list` and the last run. Never edit by hand.',
    '',
    '## Summary',
    '',
    '| Area | Requirements | Covered | Deferred | Cases | Planned | Automated | Passed | Failed | Flaky | Not run |',
    '|---|---|---|---|---|---|---|---|---|---|---|'
  ]
  for (const plan of input.plans) {
    const coveredCount = plan.requirements.filter(
      requirement => requirementCoverage(plan, requirement.id, automated) === 'covered'
    ).length
    const count = (state: CaseOutcome) =>
      plan.cases.filter(plannedCase => outcome(plannedCase.id) === state).length
    lines.push(
      `| ${plan.area} | ${plan.requirements.length} | ${coveredCount} | ${plan.requirements.filter(r => r.status === 'deferred').length} | ` +
        `${plan.cases.length} | ${plan.cases.filter(c => c.automation === 'planned').length} | ${plan.cases.filter(automated).length} | ` +
        `${count('passed')} | ${count('failed')} | ${count('flaky')} | ${count('not run')} |`
    )
  }

  for (const plan of input.plans) {
    lines.push('', `## ${plan.area}`, '', `Source: \`${plan.file}\``, '', '### Requirements', '')
    lines.push('| ID | Requirement | Coverage | Cases | Last result |', '|---|---|---|---|---|')
    for (const requirement of plan.requirements) {
      const cases = plan.cases.filter(plannedCase => plannedCase.covers.includes(requirement.id))
      const coverage =
        requirement.status === 'deferred'
          ? `deferred: ${requirement.deferReason ?? ''}`
          : requirementCoverage(plan, requirement.id, automated)
      lines.push(
        `| ${requirement.id} | ${cell(requirement.text)} | ${cell(coverage)} | ${cases.map(c => c.id).join(', ') || '—'} | ` +
          `${worstOutcome(cases.map(c => outcome(c.id)))} |`
      )
    }
    lines.push(
      '',
      '### Cases',
      '',
      '| ID | Title | Layer | Priority | Intent | Automated | Tests | Last result |',
      '|---|---|---|---|---|---|---|---|'
    )
    for (const plannedCase of plan.cases) {
      const tests = testsByCase.get(plannedCase.id) ?? []
      const files = [...new Set(tests.map(test => `${test.file}:${test.line}`))]
      lines.push(
        `| ${plannedCase.id} | ${cell(plannedCase.title)} | ${plannedCase.layer} | ${plannedCase.priority} | ${plannedCase.automation} | ` +
          `${tests.length ? 'yes' : 'no'} | ${files.map(file => `\`${file}\``).join('<br>') || '—'} | ${outcome(plannedCase.id)} |`
      )
    }
  }
  return `${lines.join('\n')}\n`
}

function requirementCoverage(
  plan: TestPlan,
  requirementId: string,
  automated: (plannedCase: PlannedCase) => boolean
): 'covered' | 'planned' | 'uncovered' | 'deferred' {
  const requirement = plan.requirements.find(candidate => candidate.id === requirementId)
  if (requirement?.status === 'deferred') return 'deferred'
  const cases = plan.cases.filter(plannedCase => plannedCase.covers.includes(requirementId))
  if (cases.some(automated)) return 'covered'
  return cases.length ? 'planned' : 'uncovered'
}

function worstOutcome(outcomes: CaseOutcome[]): CaseOutcome {
  if (!outcomes.length) return 'not run'
  for (const state of ['failed', 'flaky', 'not run'] as const) {
    if (outcomes.includes(state)) return state
  }
  return 'passed'
}
